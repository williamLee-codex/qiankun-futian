CREATE TABLE IF NOT EXISTS platform.admin_audit_logs (
  id text NOT NULL,
  actor_id text NOT NULL,
  actor_roles jsonb NOT NULL DEFAULT '[]'::jsonb,
  action text NOT NULL,
  target_type text NOT NULL,
  target_id text NOT NULL,
  result text NOT NULL,
  occurred_at timestamptz NOT NULL,
  metadata jsonb NOT NULL DEFAULT '{}'::jsonb,
  correlation_id text NOT NULL,
  request_id text NOT NULL,
  source text NOT NULL DEFAULT 'admin-console',
  created_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT admin_audit_logs_pkey PRIMARY KEY (id),
  CONSTRAINT admin_audit_logs_actor_id_check CHECK (btrim(actor_id) <> ''),
  CONSTRAINT admin_audit_logs_actor_roles_check CHECK (jsonb_typeof(actor_roles) = 'array'),
  CONSTRAINT admin_audit_logs_action_check CHECK (action ~ '^admin\.[a-z0-9_.-]+$'),
  CONSTRAINT admin_audit_logs_result_check CHECK (result IN ('denied', 'failed', 'succeeded')),
  CONSTRAINT admin_audit_logs_source_check CHECK (source = 'admin-console'),
  CONSTRAINT admin_audit_logs_metadata_check CHECK (jsonb_typeof(metadata) = 'object'),
  CONSTRAINT admin_audit_logs_correlation_id_check CHECK (btrim(correlation_id) <> ''),
  CONSTRAINT admin_audit_logs_request_id_check CHECK (btrim(request_id) <> '')
);

